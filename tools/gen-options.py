#!/usr/bin/env python3
"""Generate docs/options.md and the README options summary from the
coverage table spec/<pin>/coverage.json. Re-run after the table changes:

    python3 tools/gen-options.py

Stdlib only. Rewrites docs/options.md and the README block between the
BEGIN/END OPTIONS markers; exits 1 if the markers are missing.
"""
import collections
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = sorted((ROOT / "spec").glob("v*/coverage.json"))[-1]
BEGIN, END = "<!-- BEGIN OPTIONS (tools/gen-options.py) -->", "<!-- END OPTIONS -->"

STATUS = {
    "reproduce": "Reproduced",
    "saved-data-only": "Reproduced (tested on saved data)",
    "fold": "Folded into other options",
    "client-only": "Not recoverable (client only)",
}
V1 = {"supported": "yes", "partial": "partly", "missing": "no"}
PLATFORM = {"all": "any", "linux": "Linux", "windows": "Windows"}

# Notes in coverage.json that record test history or open questions rather
# than what runlike 2.0 does. ponytail: move these into coverage.json and
# delete this dict once the table carries user-facing notes.
NOTE = {
    "--cidfile": "Printed when set. docker run fails if that file already exists, so remove it or change the path before running the copy.",
    "--platform": "Printed only when the image's platform differs from the daemon's native one.",
    "--blkio-weight": "Python 1.6.3 ignores it.",
    "--gpus": "Stored as a device request. Python 1.6.3 ignores it.",
    "--use-api-socket": "Docker turns it into a socket mount plus DOCKER_CONFIG; runlike prints --use-api-socket back when both are present. The credentials Docker copied in cannot be read back.",
}


def note(o):
    n = NOTE.get(o["flag"], o["note"])
    n = re.sub(r"\s*\((?:runlike-\w+(?:, )?)+\)", "", n)  # internal tracker IDs
    n = re.sub(r"runlike-\w+, ", "", n)  # tracker IDs before a GitHub ref
    n = re.sub(r"GitHub #(\d+)", r"[#\1](https://github.com/lavie/runlike/issues/\1)", n)
    return n.replace("|", "\\|")


def flag(o):
    return f"`{o['short']}, {o['flag']}`" if o["short"] else f"`{o['flag']}`"


def main():
    data = json.loads(SPEC.read_text())
    pin, opts = data["docker_cli_version"], data["options"]
    count = collections.Counter(o["kind"] for o in opts)
    ref = f"[docker run reference for Docker CLI {pin}](../{SPEC.parent.relative_to(ROOT)}/container_run.md)"

    rows = [
        f"| {flag(o)} | {PLATFORM[o['platform']]} | {STATUS[o['kind']]} | {V1[o['python_1_6_3']]} | {note(o)} |"
        for o in opts
    ]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/options.md").write_text(
        f"""<!-- Generated by tools/gen-options.py from {SPEC.relative_to(ROOT)}. Do not edit. -->
# `docker run` options in runlike 2.0

All {len(opts)} options of `docker run` in Docker CLI {pin} (source: the {ref}).

- **Reproduced**: runlike reads the value from `docker inspect` and prints the
  option. Tested by recreating a container on a real Docker daemon and comparing
  both containers' inspect output.
- **Reproduced (tested on saved data)**: same, but the test machines cannot
  create such a container (Windows-only options, kernel features they lack), so
  the test uses inspect output saved from a real daemon.
- **Folded into other options**: the option is expanded by the docker client
  and stored as other settings, which runlike prints instead.
- **Not recoverable (client only)**: the option only changes what the docker
  client does while it runs; the daemon never stores it.
- **1.6.3**: whether the last Python release handled it. The notes say how.

| Option | Platform | runlike 2.0 | 1.6.3 | Notes |
|---|---|---|---|---|
""" + "\n".join(rows) + "\n")

    summary = f"""{BEGIN}
runlike 2.0 covers all {len(opts)} options of `docker run` in Docker CLI {pin}:

| Status | Options |
|---|---|
| Reproduced | {count['reproduce']} |
| Reproduced, tested on saved data (Windows-only, or kernel features the test machines lack) | {count['saved-data-only']} |
| Folded into other options | {count['fold']}: {', '.join(f'`{o["flag"]}`' for o in opts if o['kind'] == 'fold')} |
| Not recoverable (client only) | {count['client-only']}: {', '.join(f'`{o["flag"]}`' for o in opts if o['kind'] == 'client-only')} |

Every option, with notes: [docs/options.md](docs/options.md).
{END}"""
    readme = ROOT / "README.md"
    text = readme.read_text()
    if BEGIN not in text or END not in text:
        sys.exit(f"{readme}: missing markers {BEGIN} / {END}")
    head, rest = text.split(BEGIN, 1)
    readme.write_text(head + summary + rest.split(END, 1)[1])


if __name__ == "__main__":
    main()
